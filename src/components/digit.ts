export function getGlyph(char: string | number | undefined): number[][] | undefined {
    if (char === undefined || char === null || char === '' || char === ' ') return undefined;
    const str = String(char);
    if (/^\d$/.test(str)) {
        return digit[Number(str)];
    }
    if (str === ':') {
        return digit[10];
    }
    return GLYPHS[str] ?? GLYPHS[str.toUpperCase()];
}
